import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {loadPlaywright} from './playwright-module.mjs';
const {chromium}=await loadPlaywright();

const base=process.env.TRAINING_URL??'http://127.0.0.1:4251';
const out=path.resolve(process.env.TRAINING_EVIDENCE??'output/cue-training-v8.4.0/browser-01');
await fs.mkdir(out,{recursive:false});
const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-webgl']});
const context=await browser.newContext({viewport:{width:1440,height:960},deviceScaleFactor:1});
const page=await context.newPage(),errors=[],checks=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
const snapshot=()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
try{
  await context.addInitScript(()=>{localStorage.setItem('training-save-sentinel','do-not-change');});
  const response=await page.goto(base+'/training.html',{waitUntil:'networkidle',timeout:90000});
  check('training room is available',response.status()===200);
  await page.waitForFunction(()=>window.render_game_to_text&&JSON.parse(window.render_game_to_text()).connected,{timeout:120000});
  await page.screenshot({path:path.join(out,'01-room.png')});
  let state=await snapshot();
  check('independent session ready',state.experiment.phase==='training');
  check('probe unavailable before actual learning',await page.locator('#start-probe').isDisabled());
  const initialId=state.experiment.id;
  await page.locator('#pause').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.paused);
  await page.locator('#emit-a').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.emission==='A');
  const before=await snapshot();
  check('A emitter displayed',before.rendering.cueMarkers?.count===1);
  await page.locator('#emit-b').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.emission==='B');
  state=await snapshot();
  check('paused emission creates no feeding',state.experiment.actualFeedingSeconds===before.experiment.actualFeedingSeconds);
  check('paused emission creates no teaching',state.experiment.teachingEvents===before.experiment.teachingEvents);
  check('paused emission keeps body',JSON.stringify(state.actor.position)===JSON.stringify(before.actor.position));
  await page.locator('#emit-a').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.emission==='A');
  await page.locator('#pause').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.canProbe,{timeout:120000});
  await page.screenshot({path:path.join(out,'02-fed.png')});
  const trained=await snapshot();
  check('actual food teaches A',trained.experiment.cueTraining.A.actualFeedingSeconds>0&&trained.experiment.cueTraining.A.teachingEvents>0&&trained.experiment.cueTraining.A.changedSynapses>0);
  await page.locator('#start-probe').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.phase==='probing');
  await page.locator('#pause').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.paused);
  const paused=await snapshot();
  await page.waitForTimeout(700);
  const afterPause=await snapshot();
  check('probe freezes while paused',afterPause.experiment.probe.elapsed===paused.experiment.probe.elapsed);
  check('both real cue markers shown',afterPause.rendering.cueMarkers.count===2);
  check('no food remains during observation',Object.values(afterPause.living.care.foods).every(amount=>amount===0));
  await page.screenshot({path:path.join(out,'03-probe.png')});
  await page.locator('#pause').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.phase==='result',{timeout:120000});
  const result=await snapshot();
  check('complete 20 simulation seconds',result.experiment.probe.result.completed&&result.experiment.probe.result.elapsed>=19.99);
  check('probe restoration confirmed',result.experiment.probe.result.inventoryRestored&&result.experiment.probe.result.weightsUnchanged);
  check('no unsupported learned-success label',!(/已学会|实验成功|记忆强度/.test(await page.locator('#result').innerText())));
  await page.screenshot({path:path.join(out,'04-result.png')});
  await page.locator('#swap-probe').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.phase==='probing'&&JSON.parse(window.render_game_to_text()).experiment.probe.swapped);
  await page.locator('#end-probe').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).experiment.phase!=='probing');
  const aborted=await snapshot();
  check('early exit restores food',aborted.experiment.probe.result?.inventoryRestored===true);
  await page.locator('#new-experiment').click();
  await page.locator('#reset-cancel').click();
  check('cancel keeps experiment',(await snapshot()).experiment.id===initialId);
  await page.locator('#new-experiment').click();
  await page.locator('#reset-confirm').click();
  await page.waitForFunction(id=>JSON.parse(window.render_game_to_text()).experiment.id!==id,initialId);
  state=await snapshot();
  check('new experiment clears training evidence',state.experiment.actualFeedingSeconds===0&&state.experiment.teachingEvents===0&&state.experiment.canProbe===false);
  const resetId=state.experiment.id;
  await page.locator('#new-experiment').click();await page.keyboard.press('Escape');await page.waitForTimeout(300);
  check('Escape after a confirmed reset keeps current experiment',(await snapshot()).experiment.id===resetId);
  check('daily save sentinel preserved',await page.evaluate(()=>localStorage.getItem('training-save-sentinel'))==='do-not-change');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(out,'05-mobile.png')});
  check('mobile has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.locator('#emit-b').scrollIntoViewIfNeeded();
  check('mobile emission button usable',await page.locator('#emit-b').isVisible());
  await page.goto(base+'/',{waitUntil:'networkidle',timeout:90000});
  check('daily room exposes training entrance',await page.locator('a.training-entry').getAttribute('href')==='/training.html');
  check('zero browser errors',errors.length===0);
  await fs.writeFile(path.join(out,'receipt.json'),JSON.stringify({version:'8.4.0',pass:true,checks,errors,trained:trained.experiment,result:result.experiment,aborted:aborted.experiment},null,2));
  console.log(JSON.stringify({pass:true,checks:checks.length,errors:errors.length,out}));
}catch(error){
  await page.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});
  await fs.writeFile(path.join(out,'receipt.json'),JSON.stringify({version:'8.4.0',pass:false,checks,errors,error:error.stack,state:await snapshot().catch(()=>null)},null,2));
  throw error;
}finally{await browser.close();}
